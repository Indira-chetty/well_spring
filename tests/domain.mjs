import assert from 'node:assert/strict';
import {seed,mutate} from '../app/domain.ts';
let s=seed();
assert.throws(()=>mutate(s,'draft',{id:'kijana'},'Owner'),/Verify/);
mutate(s,'pursue',{id:'nlf'},'Owner');assert.equal(s.funders.find(f=>f.id==='nlf').stage,'Researching');
assert.throws(()=>mutate(s,'reconcile',{id:'B-10',decision:'approve'},'Owner'),/investigation/);
mutate(s,'reconcile',{id:'B-04',decision:'approve'},'Owner');
mutate(s,'briefing',{},'Owner');assert.match(s.drafts[0].text,/5,000/);
mutate(s,'draft',{id:'nepal',kind:'Funder report'},'Owner');const d=s.drafts[0];
mutate(s,'approveDraft',{id:d.id,status:'Approved'},'Owner');assert.equal(d.reviewedBy,'Owner');
mutate(s,'editDraft',{id:d.id,text:'Edited evidence'},'Owner');assert.equal(d.status,'Needs review');assert.equal(d.reviewedBy,null);
mutate(s,'approveDraft',{id:d.id,status:'Approved'},'Owner');
mutate(s,'project',{id:'nepal',results:'Updated results',challenges:'Pending verification'},'Owner');assert.equal(d.status,'Needs review');assert.equal(s.projects[1].verified,false);
assert.throws(()=>mutate(s,'reply',{id:'s2'},'Owner'),/consent/);
assert.throws(()=>mutate(s,'verify',{id:'nepal',note:''},'Owner'),/Explain/);
s.trained=false;assert.throws(()=>mutate(s,'draft',{id:'nepal'},'Owner'),/training/);
assert.throws(()=>mutate(s,'training',{answers:[0,0,0]},'Owner'),/correct/);
mutate(s,'training',{answers:[0,1,1]},'Owner');assert.equal(s.trained,true);
mutate(s,'decision',{decision:'Revise',note:'Evidence is not yet sufficient'},'Owner');assert.equal(s.decisions[0].evidence.approvedMatches,1);
assert.ok(s.activity.every(a=>a.id&&a.at&&a.title));
console.log('Passed: approval resets, evidence gates, consent blocks, training, finance exceptions, briefing totals and decision evidence.');
